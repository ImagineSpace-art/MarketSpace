CREATE OR REPLACE FUNCTION public.enforce_probation_listing_limit()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  seller_store public.stores%ROWTYPE;
  active_count INTEGER;
BEGIN
  IF NEW.store_id IS NULL
     OR NEW.moderation_status <> 'approved'
     OR lower(COALESCE(NEW.status, '')) NOT IN ('available', 'active') THEN
    RETURN NEW;
  END IF;

  SELECT * INTO seller_store
  FROM public.stores
  WHERE id = NEW.store_id
  FOR UPDATE;

  IF seller_store.status <> 'approved' THEN
    RAISE EXCEPTION 'Listings can only be published by approved stores';
  END IF;

  IF seller_store.probation_state = 'probation' THEN
    SELECT COUNT(*) INTO active_count
    FROM public.listings
    WHERE store_id = NEW.store_id
      AND moderation_status = 'approved'
      AND lower(COALESCE(status, '')) IN ('available', 'active')
      AND id IS DISTINCT FROM NEW.id;

    IF active_count >= seller_store.active_listing_limit THEN
      RAISE EXCEPTION 'This store has reached its active listing limit of %',
        seller_store.active_listing_limit;
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS listings_probation_limit ON public.listings;
CREATE TRIGGER listings_probation_limit
  BEFORE INSERT OR UPDATE OF store_id, status, moderation_status ON public.listings
  FOR EACH ROW EXECUTE FUNCTION public.enforce_probation_listing_limit();

CREATE OR REPLACE FUNCTION public.expire_marketplace_listings()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_count INTEGER := 0;
BEGIN
  UPDATE public.listings l
  SET status = 'Expired'
  WHERE l.moderation_status = 'approved'
    AND COALESCE(l.status, 'Available') <> 'Expired'
    AND public.listing_is_expired(l)
    AND lower(COALESCE(l.status, '')) NOT IN ('sold', 'deleted');
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

CREATE OR REPLACE FUNCTION public.enforce_listing_expiration()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.moderation_status = 'approved'
     AND public.listing_is_expired(NEW)
     AND lower(COALESCE(NEW.status, '')) NOT IN ('sold', 'deleted') THEN
    NEW.status := 'Expired';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS enforce_listing_expiration ON public.listings;
CREATE TRIGGER enforce_listing_expiration
  BEFORE INSERT OR UPDATE OF status, last_renewed_at, created_at, renewal_frequency, use_global_renewal, user_id, moderation_status
  ON public.listings
  FOR EACH ROW EXECUTE FUNCTION public.enforce_listing_expiration();
