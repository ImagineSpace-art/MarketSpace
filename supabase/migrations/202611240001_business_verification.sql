-- Business verification: evidence-based "Business verified" level for approved stores.
-- A store is verified only after a moderator has (1) verified a business document,
-- (2) passed a live video check with a live-presence code, and (3) confirmed an
-- endorsement by phone. Every decision is written to an append-only audit log.
-- Writes happen only through the business-verification Edge Function (service role).

ALTER TABLE public.stores
  ADD COLUMN IF NOT EXISTS business_verified_at TIMESTAMPTZ;

-- ---------------------------------------------------------------------------
-- Evidence tables
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.store_business_documents (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  store_id UUID NOT NULL REFERENCES public.stores(id) ON DELETE CASCADE,
  doc_type TEXT NOT NULL CHECK (doc_type IN (
    'pacra_certificate', 'zra_tpin', 'council_licence', 'market_permit', 'lease_or_landlord_letter'
  )),
  doc_number TEXT NOT NULL CHECK (char_length(doc_number) BETWEEN 3 AND 40),
  file_path TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'verified', 'rejected')),
  checked_against_source BOOLEAN NOT NULL DEFAULT false,
  reason TEXT CHECK (reason IS NULL OR char_length(reason) <= 500),
  reviewed_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS store_business_documents_one_pending_idx
  ON public.store_business_documents (store_id) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS store_business_documents_store_idx
  ON public.store_business_documents (store_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.store_video_checks (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  store_id UUID NOT NULL REFERENCES public.stores(id) ON DELETE CASCADE,
  challenge_code TEXT NOT NULL,
  code_expires_at TIMESTAMPTZ NOT NULL,
  originals_seen BOOLEAN NOT NULL DEFAULT false,
  shop_shown BOOLEAN NOT NULL DEFAULT false,
  code_matched BOOLEAN NOT NULL DEFAULT false,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'passed', 'failed')),
  notes TEXT CHECK (notes IS NULL OR char_length(notes) <= 500),
  created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  reviewed_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS store_video_checks_one_pending_idx
  ON public.store_video_checks (store_id) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS store_video_checks_store_idx
  ON public.store_video_checks (store_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.store_endorsements (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  store_id UUID NOT NULL REFERENCES public.stores(id) ON DELETE CASCADE,
  endorser_name TEXT NOT NULL CHECK (char_length(endorser_name) BETWEEN 2 AND 100),
  endorser_role TEXT NOT NULL CHECK (char_length(endorser_role) BETWEEN 2 AND 100),
  endorser_phone TEXT NOT NULL CHECK (endorser_phone ~ '^\+?[0-9 ]{9,15}$'),
  letter_path TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'not_confirmed')),
  phoned_at TIMESTAMPTZ,
  notes TEXT CHECK (notes IS NULL OR char_length(notes) <= 500),
  reviewed_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS store_endorsements_one_pending_idx
  ON public.store_endorsements (store_id) WHERE status = 'pending';
CREATE INDEX IF NOT EXISTS store_endorsements_store_idx
  ON public.store_endorsements (store_id, created_at DESC);

