CREATE OR REPLACE FUNCTION public.prevent_store_owner_status_changes()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF current_user NOT IN ('service_role', 'postgres', 'supabase_admin') THEN
    IF TG_OP = 'INSERT' THEN
      IF NOT EXISTS (SELECT 1 FROM public.stores s WHERE s.user_id = NEW.user_id) THEN
        RAISE EXCEPTION 'Stores can only be created by the registration service';
      END IF;
    ELSIF
      NEW.status IS DISTINCT FROM OLD.status
      OR NEW.id IS DISTINCT FROM OLD.id
      OR NEW.user_id IS DISTINCT FROM OLD.user_id
      OR NEW.subdomain IS DISTINCT FROM OLD.subdomain
      OR NEW.store_type IS DISTINCT FROM OLD.store_type
      OR NEW.verified_id IS DISTINCT FROM OLD.verified_id
      OR NEW.verified_location IS DISTINCT FROM OLD.verified_location
      OR NEW.registered_business IS DISTINCT FROM OLD.registered_business
      OR NEW.business_verified_at IS DISTINCT FROM OLD.business_verified_at
      OR NEW.storefront_latitude IS DISTINCT FROM OLD.storefront_latitude
      OR NEW.storefront_longitude IS DISTINCT FROM OLD.storefront_longitude
      OR NEW.business_registration_number IS DISTINCT FROM OLD.business_registration_number
      OR NEW.probation_state IS DISTINCT FROM OLD.probation_state
      OR NEW.active_listing_limit IS DISTINCT FROM OLD.active_listing_limit
      OR NEW.trust_promote_after_listings IS DISTINCT FROM OLD.trust_promote_after_listings
      OR NEW.template_id IS DISTINCT FROM OLD.template_id
      OR NEW.template_content IS DISTINCT FROM OLD.template_content
    THEN
      RAISE EXCEPTION 'Store review, trust, and template fields can only be changed by trusted services';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------------
-- Review functions (service role only). Each checks the reviewer is a moderator
-- and is not the store owner, then writes the decision and an audit record.
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.business_assert_reviewer(p_store_id UUID, p_reviewer_id UUID)
RETURNS public.stores
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  target_store public.stores%ROWTYPE;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.store_admins WHERE user_id = p_reviewer_id) THEN
    RAISE EXCEPTION 'Reviewer is not a moderator';
  END IF;
  SELECT * INTO target_store FROM public.stores WHERE id = p_store_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Store not found';
  END IF;
  IF target_store.user_id = p_reviewer_id THEN
    RAISE EXCEPTION 'Moderators cannot review their own store';
  END IF;
  IF target_store.status IS DISTINCT FROM 'approved' THEN
    RAISE EXCEPTION 'Only approved stores can be business verified';
  END IF;
  RETURN target_store;
END;
$$;

CREATE OR REPLACE FUNCTION public.business_review_document(
  p_document_id UUID,
  p_reviewer_id UUID,
  p_decision TEXT,
  p_checked_against_source BOOLEAN,
  p_reason TEXT DEFAULT ''
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  doc public.store_business_documents%ROWTYPE;
  clean_reason TEXT := trim(COALESCE(p_reason, ''));
BEGIN
  IF p_decision NOT IN ('verified', 'rejected') THEN
    RAISE EXCEPTION 'Invalid document decision';
  END IF;
  IF char_length(clean_reason) > 500 THEN
    RAISE EXCEPTION 'The reason must be 500 characters or fewer';
  END IF;
  IF p_decision = 'rejected' AND clean_reason = '' THEN
    RAISE EXCEPTION 'A reason is required when rejecting a document';
  END IF;
  IF p_decision = 'verified' AND p_checked_against_source IS NOT TRUE THEN
    RAISE EXCEPTION 'Confirm that the document was checked against the official source';
  END IF;

  SELECT * INTO doc FROM public.store_business_documents WHERE id = p_document_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Document not found';
  END IF;
  PERFORM public.business_assert_reviewer(doc.store_id, p_reviewer_id);

  UPDATE public.store_business_documents
  SET status = p_decision,
      checked_against_source = (p_decision = 'verified'),
      reason = NULLIF(clean_reason, ''),
      reviewed_by = p_reviewer_id,
      reviewed_at = statement_timestamp()
  WHERE id = p_document_id AND status = 'pending'
  RETURNING * INTO doc;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Document is no longer pending';
  END IF;

  INSERT INTO public.business_verification_audit_log (store_id, actor_user_id, action, reason, details)
  VALUES (
    doc.store_id, p_reviewer_id,
    CASE WHEN p_decision = 'verified' THEN 'document_verified' ELSE 'document_rejected' END,
    NULLIF(clean_reason, ''),
    jsonb_build_object('document_id', doc.id, 'doc_type', doc.doc_type, 'doc_number', doc.doc_number)
  );

  RETURN jsonb_build_object('id', doc.id, 'status', doc.status);
END;
$$;

CREATE OR REPLACE FUNCTION public.business_start_video_check(p_store_id UUID, p_reviewer_id UUID)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  check_row public.store_video_checks%ROWTYPE;
  new_code TEXT := 'MS-' || lpad((floor(random() * 9000) + 1000)::INT::TEXT, 4, '0');
BEGIN
  PERFORM public.business_assert_reviewer(p_store_id, p_reviewer_id);

  -- Replace any earlier unfinished check so only one live code exists.
  UPDATE public.store_video_checks
  SET status = 'failed', notes = 'Replaced by a new check', reviewed_by = p_reviewer_id, reviewed_at = statement_timestamp()
  WHERE store_id = p_store_id AND status = 'pending';

  INSERT INTO public.store_video_checks (store_id, challenge_code, code_expires_at, created_by)
  VALUES (p_store_id, new_code, statement_timestamp() + interval '30 minutes', p_reviewer_id)
  RETURNING * INTO check_row;

  INSERT INTO public.business_verification_audit_log (store_id, actor_user_id, action, details)
  VALUES (p_store_id, p_reviewer_id, 'video_check_started', jsonb_build_object('check_id', check_row.id));

  RETURN jsonb_build_object(
    'id', check_row.id,
    'challenge_code', check_row.challenge_code,
    'code_expires_at', check_row.code_expires_at
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.business_record_video_check(
  p_check_id UUID,
  p_reviewer_id UUID,
  p_decision TEXT,
  p_originals_seen BOOLEAN,
  p_shop_shown BOOLEAN,
  p_code_matched BOOLEAN,
  p_notes TEXT DEFAULT ''
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  check_row public.store_video_checks%ROWTYPE;
  clean_notes TEXT := trim(COALESCE(p_notes, ''));
BEGIN
  IF p_decision NOT IN ('passed', 'failed') THEN
    RAISE EXCEPTION 'Invalid video check decision';
  END IF;
  IF char_length(clean_notes) > 500 THEN
    RAISE EXCEPTION 'The notes must be 500 characters or fewer';
  END IF;

  SELECT * INTO check_row FROM public.store_video_checks WHERE id = p_check_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Video check not found';
  END IF;
  PERFORM public.business_assert_reviewer(check_row.store_id, p_reviewer_id);

  IF p_decision = 'passed' THEN
    IF p_originals_seen IS NOT TRUE OR p_shop_shown IS NOT TRUE OR p_code_matched IS NOT TRUE THEN
      RAISE EXCEPTION 'All three video checks must be confirmed before the check can pass';
    END IF;
    IF check_row.code_expires_at < statement_timestamp() THEN
      RAISE EXCEPTION 'The live-presence code has expired. Start a new video check';
    END IF;
  ELSIF clean_notes = '' THEN
    RAISE EXCEPTION 'Notes are required when a video check fails';
  END IF;

  UPDATE public.store_video_checks
  SET status = p_decision,
      originals_seen = COALESCE(p_originals_seen, false),
      shop_shown = COALESCE(p_shop_shown, false),
      code_matched = COALESCE(p_code_matched, false),
      notes = NULLIF(clean_notes, ''),
      reviewed_by = p_reviewer_id,
      reviewed_at = statement_timestamp()
  WHERE id = p_check_id AND status = 'pending'
  RETURNING * INTO check_row;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Video check is no longer pending';
  END IF;

  INSERT INTO public.business_verification_audit_log (store_id, actor_user_id, action, reason, details)
  VALUES (
    check_row.store_id, p_reviewer_id,
    CASE WHEN p_decision = 'passed' THEN 'video_check_passed' ELSE 'video_check_failed' END,
    NULLIF(clean_notes, ''),
    jsonb_build_object('check_id', check_row.id)
  );

  RETURN jsonb_build_object('id', check_row.id, 'status', check_row.status);
END;
$$;

CREATE OR REPLACE FUNCTION public.business_review_endorsement(
  p_endorsement_id UUID,
  p_reviewer_id UUID,
  p_decision TEXT,
  p_phoned BOOLEAN,
  p_notes TEXT DEFAULT ''
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  endorsement public.store_endorsements%ROWTYPE;
  clean_notes TEXT := trim(COALESCE(p_notes, ''));
BEGIN
  IF p_decision NOT IN ('confirmed', 'not_confirmed') THEN
    RAISE EXCEPTION 'Invalid endorsement decision';
  END IF;
  IF char_length(clean_notes) > 500 THEN
    RAISE EXCEPTION 'The notes must be 500 characters or fewer';
  END IF;
  IF p_decision = 'confirmed' AND p_phoned IS NOT TRUE THEN
    RAISE EXCEPTION 'Phone the endorser before confirming the endorsement';
  END IF;
  IF p_decision = 'not_confirmed' AND clean_notes = '' THEN
    RAISE EXCEPTION 'Notes are required when an endorsement is not confirmed';
  END IF;

  SELECT * INTO endorsement FROM public.store_endorsements WHERE id = p_endorsement_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Endorsement not found';
  END IF;
  PERFORM public.business_assert_reviewer(endorsement.store_id, p_reviewer_id);

  UPDATE public.store_endorsements
  SET status = p_decision,
      phoned_at = CASE WHEN p_phoned IS TRUE THEN statement_timestamp() ELSE NULL END,
      notes = NULLIF(clean_notes, ''),
      reviewed_by = p_reviewer_id,
      reviewed_at = statement_timestamp()
  WHERE id = p_endorsement_id AND status = 'pending'
  RETURNING * INTO endorsement;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Endorsement is no longer pending';
  END IF;

  INSERT INTO public.business_verification_audit_log (store_id, actor_user_id, action, reason, details)
  VALUES (
    endorsement.store_id, p_reviewer_id,
    CASE WHEN p_decision = 'confirmed' THEN 'endorsement_confirmed' ELSE 'endorsement_not_confirmed' END,
    NULLIF(clean_notes, ''),
    jsonb_build_object('endorsement_id', endorsement.id, 'endorser_name', endorsement.endorser_name)
  );

  RETURN jsonb_build_object('id', endorsement.id, 'status', endorsement.status);
END;
$$;

CREATE OR REPLACE FUNCTION public.business_grant_verification(p_store_id UUID, p_reviewer_id UUID)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  granted_at TIMESTAMPTZ := statement_timestamp();
BEGIN
  PERFORM public.business_assert_reviewer(p_store_id, p_reviewer_id);

  IF NOT EXISTS (SELECT 1 FROM public.store_business_documents WHERE store_id = p_store_id AND status = 'verified') THEN
    RAISE EXCEPTION 'A verified business document is required';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.store_video_checks WHERE store_id = p_store_id AND status = 'passed') THEN
    RAISE EXCEPTION 'A passed video check is required';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.store_endorsements WHERE store_id = p_store_id AND status = 'confirmed') THEN
    RAISE EXCEPTION 'A confirmed endorsement is required';
  END IF;

  UPDATE public.stores SET business_verified_at = granted_at WHERE id = p_store_id;

  INSERT INTO public.business_verification_audit_log (store_id, actor_user_id, action)
  VALUES (p_store_id, p_reviewer_id, 'business_verified_granted');

  RETURN jsonb_build_object('store_id', p_store_id, 'business_verified_at', granted_at);
END;
$$;

CREATE OR REPLACE FUNCTION public.business_revoke_verification(
  p_store_id UUID,
  p_reviewer_id UUID,
  p_reason TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  clean_reason TEXT := trim(COALESCE(p_reason, ''));
BEGIN
  IF clean_reason = '' OR char_length(clean_reason) > 500 THEN
    RAISE EXCEPTION 'A reason of 500 characters or fewer is required to revoke verification';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.store_admins WHERE user_id = p_reviewer_id) THEN
    RAISE EXCEPTION 'Reviewer is not a moderator';
  END IF;

  UPDATE public.stores SET business_verified_at = NULL
  WHERE id = p_store_id AND business_verified_at IS NOT NULL;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'This store is not business verified';
  END IF;

  INSERT INTO public.business_verification_audit_log (store_id, actor_user_id, action, reason)
  VALUES (p_store_id, p_reviewer_id, 'business_verified_revoked', clean_reason);

  RETURN jsonb_build_object('store_id', p_store_id, 'business_verified_at', NULL);
END;
$$;

