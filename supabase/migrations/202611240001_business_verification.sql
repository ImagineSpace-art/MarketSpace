CREATE TABLE IF NOT EXISTS public.business_verification_audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id UUID NOT NULL,
  actor_user_id UUID NOT NULL,
  action TEXT NOT NULL CHECK (action IN (
    'document_submitted', 'document_verified', 'document_rejected',
    'video_check_started', 'video_check_passed', 'video_check_failed',
    'endorsement_submitted', 'endorsement_confirmed', 'endorsement_not_confirmed',
    'business_verified_granted', 'business_verified_revoked'
  )),
  reason TEXT CHECK (reason IS NULL OR char_length(reason) <= 500),
  details JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS business_verification_audit_store_idx
  ON public.business_verification_audit_log (store_id, created_at DESC);

CREATE OR REPLACE FUNCTION public.prevent_business_verification_audit_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF current_user NOT IN ('postgres', 'supabase_admin') THEN
    RAISE EXCEPTION 'Business verification audit records are append-only';
  END IF;
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

