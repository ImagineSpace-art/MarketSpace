CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;

CREATE TABLE IF NOT EXISTS public.store_guest_conversations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  store_id UUID NOT NULL REFERENCES public.stores(id) ON DELETE CASCADE,
  listing_id BIGINT REFERENCES public.listings(id) ON DELETE SET NULL,
  guest_name TEXT NOT NULL CHECK (char_length(BTRIM(guest_name)) BETWEEN 1 AND 100),
  guest_contact TEXT NOT NULL CHECK (char_length(BTRIM(guest_contact)) BETWEEN 3 AND 254),
  resume_secret_hash BYTEA NOT NULL,
  owner_unread BOOLEAN NOT NULL DEFAULT true,
  guest_unread BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.store_guest_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id UUID NOT NULL REFERENCES public.store_guest_conversations(id) ON DELETE CASCADE,
  sender_role TEXT NOT NULL CHECK (sender_role IN ('guest', 'owner')),
  sender_user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  content TEXT NOT NULL CHECK (char_length(BTRIM(content)) BETWEEN 1 AND 5000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS store_guest_conversations_store_updated_idx
  ON public.store_guest_conversations (store_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS store_guest_messages_conversation_created_idx
  ON public.store_guest_messages (conversation_id, created_at);

ALTER TABLE public.store_guest_conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.store_guest_messages ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.store_guest_conversations, public.store_guest_messages FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.start_store_guest_conversation(
  p_store_id UUID,
  p_listing_id BIGINT,
  p_guest_name TEXT,
  p_guest_contact TEXT,
  p_initial_message TEXT,
  p_resume_secret TEXT
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions, pg_temp
AS $$
DECLARE
  store_row public.stores%ROWTYPE;
  conversation_id UUID;
BEGIN
  IF char_length(BTRIM(COALESCE(p_guest_name, ''))) NOT BETWEEN 1 AND 100
    OR char_length(BTRIM(COALESCE(p_guest_contact, ''))) NOT BETWEEN 3 AND 254
    OR char_length(BTRIM(COALESCE(p_initial_message, ''))) NOT BETWEEN 1 AND 5000
    OR COALESCE(p_resume_secret, '') !~ '^[A-Za-z0-9_-]{43}$' THEN
    RAISE EXCEPTION 'Enter your name, a valid contact, and a message';
  END IF;

  SELECT * INTO store_row
  FROM public.stores
  WHERE id = p_store_id
    AND archived_at IS NULL
    AND (status IS NULL OR status = 'approved');
  IF NOT FOUND THEN
    RAISE EXCEPTION 'This store is not available for messaging';
  END IF;

  IF p_listing_id IS NOT NULL AND NOT EXISTS (
    SELECT 1
    FROM public.listings listing
    WHERE listing.id = p_listing_id
      AND listing.user_id = store_row.user_id
      AND (listing.store_id IS NULL OR listing.store_id = store_row.id)
      AND lower(COALESCE(listing.status, 'available')) IN ('active', 'available')
  ) THEN
    RAISE EXCEPTION 'This listing is not available for messaging';
  END IF;

  INSERT INTO public.store_guest_conversations (
    store_id,
    listing_id,
    guest_name,
    guest_contact,
    resume_secret_hash
  )
  VALUES (
    store_row.id,
    p_listing_id,
    BTRIM(p_guest_name),
    BTRIM(p_guest_contact),
    extensions.digest(p_resume_secret, 'sha256')
  )
  RETURNING id INTO conversation_id;

  INSERT INTO public.store_guest_messages (conversation_id, sender_role, content)
  VALUES (conversation_id, 'guest', BTRIM(p_initial_message));

  RETURN conversation_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.send_guest_store_message(
  p_conversation_id UUID,
  p_resume_secret TEXT,
  p_content TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions, pg_temp
AS $$
BEGIN
  IF char_length(BTRIM(COALESCE(p_content, ''))) NOT BETWEEN 1 AND 5000
    OR COALESCE(p_resume_secret, '') !~ '^[A-Za-z0-9_-]{43}$' THEN
    RAISE EXCEPTION 'Enter a message before sending';
  END IF;

  UPDATE public.store_guest_conversations
  SET owner_unread = true, guest_unread = false, updated_at = now()
  WHERE id = p_conversation_id
    AND resume_secret_hash = extensions.digest(p_resume_secret, 'sha256');
  IF NOT FOUND THEN
    RAISE EXCEPTION 'This conversation could not be found';
  END IF;

  INSERT INTO public.store_guest_messages (conversation_id, sender_role, content)
  VALUES (p_conversation_id, 'guest', BTRIM(p_content));
END;
$$;

CREATE OR REPLACE FUNCTION public.get_guest_store_conversation(
  p_conversation_id UUID,
  p_resume_secret TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions, pg_temp
AS $$
DECLARE
  conversation public.store_guest_conversations%ROWTYPE;
  result JSONB;
BEGIN
  SELECT * INTO conversation
  FROM public.store_guest_conversations
  WHERE id = p_conversation_id
    AND resume_secret_hash = extensions.digest(p_resume_secret, 'sha256');
  IF NOT FOUND THEN
    RAISE EXCEPTION 'This conversation could not be found';
  END IF;

  UPDATE public.store_guest_conversations
  SET guest_unread = false
  WHERE id = conversation.id;

  SELECT jsonb_build_object(
    'id', conversation.id,
    'store_id', conversation.store_id,
    'store_name', (SELECT shop_name FROM public.stores WHERE id = conversation.store_id),
    'listing_id', conversation.listing_id,
    'guest_name', conversation.guest_name,
    'guest_contact', conversation.guest_contact,
    'created_at', conversation.created_at,
    'updated_at', conversation.updated_at,
    'messages', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'id', message.id,
        'sender_role', message.sender_role,
        'content', message.content,
        'created_at', message.created_at
      ) ORDER BY message.created_at, message.id)
      FROM public.store_guest_messages message
      WHERE message.conversation_id = conversation.id
    ), '[]'::jsonb)
  ) INTO result;

  RETURN result;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_my_store_guest_conversations()
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  result JSONB;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Sign in to view store inquiries';
  END IF;

  SELECT COALESCE(jsonb_agg(jsonb_build_object(
    'id', conversation.id,
    'store_id', conversation.store_id,
    'store_name', store.shop_name,
    'listing_id', conversation.listing_id,
    'listing_title', listing.title,
    'guest_name', conversation.guest_name,
    'guest_contact', conversation.guest_contact,
    'owner_unread', conversation.owner_unread,
    'guest_unread', conversation.guest_unread,
    'created_at', conversation.created_at,
    'updated_at', conversation.updated_at,
    'last_message', latest.content,
    'last_sender_role', latest.sender_role
  ) ORDER BY conversation.updated_at DESC), '[]'::jsonb)
  INTO result
  FROM public.store_guest_conversations conversation
  JOIN public.stores store ON store.id = conversation.store_id
  LEFT JOIN public.listings listing ON listing.id = conversation.listing_id
  LEFT JOIN LATERAL (
    SELECT message.content, message.sender_role
    FROM public.store_guest_messages message
    WHERE message.conversation_id = conversation.id
    ORDER BY message.created_at DESC, message.id DESC
    LIMIT 1
  ) latest ON true
  WHERE store.user_id = auth.uid();

  RETURN result;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_my_store_guest_conversation(p_conversation_id UUID)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  conversation public.store_guest_conversations%ROWTYPE;
  store_name TEXT;
  result JSONB;
BEGIN
  SELECT guest_conversation.* INTO conversation
  FROM public.store_guest_conversations guest_conversation
  JOIN public.stores store ON store.id = guest_conversation.store_id
  WHERE guest_conversation.id = p_conversation_id
    AND store.user_id = auth.uid();
  IF NOT FOUND THEN
    RAISE EXCEPTION 'This conversation could not be found';
  END IF;

  SELECT shop_name INTO store_name FROM public.stores WHERE id = conversation.store_id;
  UPDATE public.store_guest_conversations
  SET owner_unread = false
  WHERE id = conversation.id;

  SELECT jsonb_build_object(
    'id', conversation.id,
    'store_id', conversation.store_id,
    'store_name', store_name,
    'listing_id', conversation.listing_id,
    'guest_name', conversation.guest_name,
    'guest_contact', conversation.guest_contact,
    'created_at', conversation.created_at,
    'updated_at', conversation.updated_at,
    'messages', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'id', message.id,
        'sender_role', message.sender_role,
        'content', message.content,
        'created_at', message.created_at
      ) ORDER BY message.created_at, message.id)
      FROM public.store_guest_messages message
      WHERE message.conversation_id = conversation.id
    ), '[]'::jsonb)
  ) INTO result;

  RETURN result;
END;
$$;

CREATE OR REPLACE FUNCTION public.send_owner_store_guest_message(
  p_conversation_id UUID,
  p_content TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF auth.uid() IS NULL OR char_length(BTRIM(COALESCE(p_content, ''))) NOT BETWEEN 1 AND 5000 THEN
    RAISE EXCEPTION 'Sign in and enter a message before sending';
  END IF;

  UPDATE public.store_guest_conversations conversation
  SET guest_unread = true, owner_unread = false, updated_at = now()
  FROM public.stores store
  WHERE conversation.id = p_conversation_id
    AND store.id = conversation.store_id
    AND store.user_id = auth.uid();
  IF NOT FOUND THEN
    RAISE EXCEPTION 'This conversation could not be found';
  END IF;

  INSERT INTO public.store_guest_messages (conversation_id, sender_role, sender_user_id, content)
  VALUES (p_conversation_id, 'owner', auth.uid(), BTRIM(p_content));
END;
$$;

