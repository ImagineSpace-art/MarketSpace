  WHERE id = p_store_id
$$;

CREATE OR REPLACE FUNCTION public.store_subdomain_available(p_subdomain TEXT, p_user_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT NOT EXISTS (
    SELECT 1
    FROM public.stores s
    WHERE lower(s.subdomain) = lower(p_subdomain)
      AND s.user_id <> p_user_id
      AND s.status <> 'rejected'
  )
  AND NOT EXISTS (
    SELECT 1
    FROM public.store_registration_drafts d
    WHERE d.user_id <> p_user_id
      AND lower(d.data #>> '{store,subdomain}') = lower(p_subdomain)
      AND d.status IN ('draft', 'pending_review')
  )
$$;

CREATE OR REPLACE FUNCTION public.consume_store_rate_limit(
  p_rate_key TEXT,
  p_action TEXT,
  p_limit INTEGER,
  p_window_seconds INTEGER
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  bucket TIMESTAMPTZ;
  updated_count INTEGER;
BEGIN
  bucket := to_timestamp(floor(extract(epoch FROM now()) / p_window_seconds) * p_window_seconds);
  INSERT INTO public.store_registration_rate_limits (rate_key, action, window_start, hit_count)
  VALUES (p_rate_key, p_action, bucket, 1)
  ON CONFLICT (rate_key, action, window_start)
  DO UPDATE SET hit_count = public.store_registration_rate_limits.hit_count + 1
  RETURNING hit_count INTO updated_count;

  DELETE FROM public.store_registration_rate_limits
  WHERE window_start < now() - interval '2 days';

  RETURN updated_count <= p_limit;
END;
$$;

