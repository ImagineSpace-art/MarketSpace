CREATE OR REPLACE FUNCTION public.enforce_probation_listing_limit()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  seller_store public.stores%ROWTYPE;
  active_count INTEGER;
BEGIN
  IF NEW.store_id IS NULL OR NEW.status NOT IN ('Available', 'Active') THEN
    RETURN NEW;
  END IF;

  SELECT * INTO seller_store
  FROM public.stores
  WHERE id = NEW.store_id
  FOR UPDATE;

  IF seller_store.status <> 'approved' THEN
    RAISE EXCEPTION 'Listings can only be published by approved stores';
  END IF;

  IF seller_store.probation_state = 'probation' THEN
    SELECT COUNT(*) INTO active_count
    FROM public.listings
    WHERE store_id = NEW.store_id
      AND status IN ('Available', 'Active')
      AND id IS DISTINCT FROM NEW.id;

    IF active_count >= seller_store.active_listing_limit THEN
      RAISE EXCEPTION 'This store has reached its active listing limit of %',
        seller_store.active_listing_limit;
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS listings_probation_limit ON public.listings;
CREATE TRIGGER listings_probation_limit
  BEFORE INSERT OR UPDATE OF store_id, status ON public.listings
  FOR EACH ROW EXECUTE FUNCTION public.enforce_probation_listing_limit();

CREATE OR REPLACE FUNCTION public.promote_trusted_stores()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  promoted_count INTEGER;
BEGIN
  UPDATE public.stores s
  SET probation_state = 'trusted',
      active_listing_limit = 2147483647,
      payout_hold_days = 0
  WHERE s.status = 'approved'
    AND s.probation_state = 'probation'
    AND s.completed_order_count >= s.trust_promote_after_orders
    AND COALESCE((
      SELECT AVG(r.rating)::NUMERIC
      FROM public.reviews r
      WHERE r.store_id = s.id
    ), 0) >= s.trust_minimum_rating;

  GET DIAGNOSTICS promoted_count = ROW_COUNT;
  RETURN promoted_count;
END;
$$;

CREATE OR REPLACE FUNCTION public.store_can_accept_order(p_store_id UUID, p_order_value NUMERIC)
