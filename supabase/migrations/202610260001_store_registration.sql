CREATE OR REPLACE FUNCTION public.enforce_store_private_upload_limits()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, storage
AS $$
DECLARE
  image_count INTEGER;
  object_size BIGINT;
  mime_type TEXT;
BEGIN
  IF NEW.bucket_id <> 'store-private' THEN
    RETURN NEW;
  END IF;

  IF (storage.foldername(NEW.name))[1] IS DISTINCT FROM auth.uid()::text THEN
    RAISE EXCEPTION 'Private verification uploads must be stored under the signed-in owner ID';
  END IF;

  mime_type := NEW.metadata->>'mimetype';
  object_size := NULLIF(NEW.metadata->>'size', '')::BIGINT;
  IF mime_type NOT IN ('image/jpeg', 'image/png', 'image/webp')
    OR object_size IS NULL OR object_size > 8388608 THEN
    RAISE EXCEPTION 'Only supported image files up to 8 MB may be uploaded';
  END IF;

  SELECT COUNT(*) INTO image_count
  FROM storage.objects o
  WHERE o.bucket_id = 'store-private'
    AND (storage.foldername(o.name))[1] = auth.uid()::text
    AND o.created_at > now() - interval '1 hour';
  IF image_count >= 12 THEN
    RAISE EXCEPTION 'The private image upload limit was reached. Retry later.';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS store_private_upload_limits ON storage.objects;
CREATE TRIGGER store_private_upload_limits
  BEFORE INSERT ON storage.objects
  FOR EACH ROW EXECUTE FUNCTION public.enforce_store_private_upload_limits();

CREATE OR REPLACE FUNCTION public.prevent_store_owner_status_changes()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF current_user <> 'service_role' AND (
    NEW.status IS DISTINCT FROM OLD.status
    OR NEW.id IS DISTINCT FROM OLD.id
    OR NEW.user_id IS DISTINCT FROM OLD.user_id
    OR NEW.subdomain IS DISTINCT FROM OLD.subdomain
    OR NEW.store_type IS DISTINCT FROM OLD.store_type
    OR NEW.verified_id IS DISTINCT FROM OLD.verified_id
    OR NEW.verified_location IS DISTINCT FROM OLD.verified_location
    OR NEW.registered_business IS DISTINCT FROM OLD.registered_business
    OR NEW.probation_state IS DISTINCT FROM OLD.probation_state
    OR NEW.active_listing_limit IS DISTINCT FROM OLD.active_listing_limit
    OR NEW.max_order_value_zmw IS DISTINCT FROM OLD.max_order_value_zmw
    OR NEW.payout_hold_days IS DISTINCT FROM OLD.payout_hold_days
    OR NEW.completed_order_count IS DISTINCT FROM OLD.completed_order_count
    OR NEW.trust_promote_after_orders IS DISTINCT FROM OLD.trust_promote_after_orders
    OR NEW.trust_minimum_rating IS DISTINCT FROM OLD.trust_minimum_rating
  ) THEN
    RAISE EXCEPTION 'Store review and trust fields can only be changed by the review service';
  END IF;
  RETURN NEW;
END;
$$;

