CREATE TABLE IF NOT EXISTS public.seller_verification_audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL,
  actor_user_id UUID NOT NULL,
  action TEXT NOT NULL CHECK (action IN ('approved', 'rejected')),
  reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (reason IS NULL OR char_length(reason) <= 500)
);

CREATE INDEX IF NOT EXISTS seller_verification_audit_log_created_idx
  ON public.seller_verification_audit_log (created_at DESC);

ALTER TABLE public.seller_verification_audit_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.seller_verification_audit_log FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.seller_verification_audit_log TO authenticated;
GRANT ALL ON public.seller_verification_audit_log TO service_role;

DROP POLICY IF EXISTS "Moderators read seller verification audit log"
  ON public.seller_verification_audit_log;
CREATE POLICY "Moderators read seller verification audit log"
  ON public.seller_verification_audit_log FOR SELECT TO authenticated
  USING (public.is_moderator());

CREATE OR REPLACE FUNCTION public.prevent_seller_verification_audit_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF current_user NOT IN ('postgres', 'supabase_admin') THEN
    RAISE EXCEPTION 'Seller verification audit records are append-only';
  END IF;
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS seller_verification_audit_log_no_mutation
  ON public.seller_verification_audit_log;
CREATE TRIGGER seller_verification_audit_log_no_mutation
  BEFORE UPDATE OR DELETE ON public.seller_verification_audit_log
  FOR EACH ROW EXECUTE FUNCTION public.prevent_seller_verification_audit_mutation();

CREATE OR REPLACE FUNCTION public.review_seller_verification(
  p_user_id UUID,
  p_reviewer_id UUID,
  p_decision TEXT,
  p_reason TEXT DEFAULT ''
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  reviewed_verification public.seller_verifications%ROWTYPE;
  clean_reason TEXT := trim(COALESCE(p_reason, ''));
BEGIN
  IF p_decision NOT IN ('approved', 'rejected') THEN
    RAISE EXCEPTION 'Invalid seller verification review decision';
  END IF;
  IF char_length(clean_reason) > 500 THEN
    RAISE EXCEPTION 'Review reason must be 500 characters or fewer';
  END IF;
  IF p_decision = 'rejected' AND clean_reason = '' THEN
    RAISE EXCEPTION 'A reason is required when rejecting a verification';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.store_admins WHERE user_id = p_reviewer_id) THEN
    RAISE EXCEPTION 'Reviewer is not a seller verification moderator';
  END IF;
  IF p_reviewer_id = p_user_id THEN
    RAISE EXCEPTION 'Moderators cannot review their own seller verification';
  END IF;

  UPDATE public.seller_verifications
  SET status = p_decision,
      reason = NULLIF(clean_reason, ''),
      reviewed_by = p_reviewer_id,
      reviewed_at = statement_timestamp(),
      updated_at = statement_timestamp()
  WHERE user_id = p_user_id
    AND status = 'pending'
  RETURNING * INTO reviewed_verification;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Seller verification is no longer pending';
  END IF;

  INSERT INTO public.seller_verification_audit_log (
    user_id, actor_user_id, action, reason
  ) VALUES (
    p_user_id, p_reviewer_id, p_decision, NULLIF(clean_reason, '')
  );

  RETURN jsonb_build_object(
    'user_id', reviewed_verification.user_id,
    'status', reviewed_verification.status,
    'reason', reviewed_verification.reason,
    'reviewed_at', reviewed_verification.reviewed_at
  );
END;
$$;

REVOKE ALL ON FUNCTION public.review_seller_verification(UUID, UUID, TEXT, TEXT)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.review_seller_verification(UUID, UUID, TEXT, TEXT)
  TO service_role;

CREATE OR REPLACE FUNCTION public.get_moderation_audit_log()
RETURNS TABLE (
  created_at TIMESTAMPTZ,
  source TEXT,
  entity_type TEXT,
  entity_id TEXT,
  actor_user_id UUID,
  action TEXT,
  reason TEXT,
  details JSONB
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF NOT public.is_moderator() THEN
    RAISE EXCEPTION 'Not authorized to read moderation audit records';
  END IF;

  RETURN QUERY
  SELECT audit.created_at, 'store_review'::TEXT,
         CASE WHEN audit.action LIKE 'store_report_%' THEN 'report' ELSE 'store_application' END,
         COALESCE(audit.details ->> 'report_id', audit.store_id::TEXT),
         audit.actor_user_id, audit.action, audit.reason, audit.details
  FROM public.store_review_audit_log audit
  UNION ALL
  SELECT audit.created_at, 'listing_moderation'::TEXT, audit.entity_type,
         audit.entity_id, audit.actor_user_id, audit.action, audit.reason, audit.details
  FROM public.moderation_audit_log audit
  UNION ALL
  SELECT audit.created_at, 'seller_verification'::TEXT, 'individual_seller'::TEXT,
         audit.user_id::TEXT, audit.actor_user_id, audit.action, audit.reason, '{}'::JSONB
  FROM public.seller_verification_audit_log audit
  ORDER BY 1 DESC
  LIMIT 500;
END;
$$;

REVOKE ALL ON FUNCTION public.get_moderation_audit_log() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_moderation_audit_log() TO authenticated;
