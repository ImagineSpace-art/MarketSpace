ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stores ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.listings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.saved_listings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chats ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reviews ENABLE ROW LEVEL SECURITY;

-- Public Read Policies
CREATE POLICY "Public Read Profiles" ON public.profiles FOR SELECT USING (true);
CREATE POLICY "Public Read Stores" ON public.stores FOR SELECT USING (true);
CREATE POLICY "Public Read Listings" ON public.listings FOR SELECT USING (true);
CREATE POLICY "Public Read Reviews" ON public.reviews FOR SELECT USING (true);

-- User Self Management Policies
CREATE POLICY "User Manage Profile" ON public.profiles FOR ALL USING (auth.uid() = user_id);
CREATE POLICY "User Manage Store" ON public.stores FOR ALL USING (auth.uid() = user_id);
CREATE POLICY "User Manage Listings" ON public.listings FOR ALL USING (auth.uid() = user_id);
CREATE POLICY "User Manage Saved Listings" ON public.saved_listings FOR ALL USING (auth.uid() = user_id);
CREATE POLICY "User Read Chats" ON public.chats FOR SELECT USING (auth.uid() = buyer_id OR auth.uid() = seller_id);
CREATE POLICY "User Insert Chats" ON public.chats FOR INSERT WITH CHECK (auth.uid() = buyer_id);
CREATE POLICY "User Read Messages" ON public.messages FOR SELECT USING (
    EXISTS (SELECT 1 FROM public.chats WHERE id = messages.chat_id AND (buyer_id = auth.uid() OR seller_id = auth.uid()))
);
CREATE POLICY "User Send Messages" ON public.messages FOR INSERT WITH CHECK (auth.uid() = sender_id);
CREATE POLICY "User Read Notifications" ON public.notifications FOR SELECT USING (user_id IS NULL OR auth.uid() = user_id);
CREATE POLICY "User Update Notifications" ON public.notifications FOR UPDATE USING (user_id IS NULL OR auth.uid() = user_id);
CREATE POLICY "User Write Reviews" ON public.reviews FOR INSERT WITH CHECK (auth.uid() = reviewer_id);

-- Secure RPC Function to let users delete their own auth account & cascading data
CREATE OR REPLACE FUNCTION delete_my_account()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    DELETE FROM auth.users WHERE id = auth.uid();
END;
$$;
